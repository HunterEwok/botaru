"""Builds the check descriptions of the suites conformance/suites/ from the tables of docs/quality.md.

A table row whose first cell is a check name of the form
`<method>:<area>/<name>` (blackbox, store, adapter, lint) becomes a suite
entry: id, method, rules and the row cells under their headers.
The implementation runner executes the entries; a suite is only data.

  python3 ci/gen_suites.py          rebuild the suites
  python3 ci/gen_suites.py --check  check that the suites match the tables
"""
import collections
import os
import re
import sys

import yaml

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, Report, id_key, id_regex, md_cells, read, registry, rel

rep = Report('check suites')
rows = [r for r in registry() if isinstance(r, dict) and isinstance(r.get('id'), str)]
ID_RE = id_regex(rows)
status = {r['id']: r for r in rows}
SRC = 'docs/quality.md'
NAME = re.compile(r'^`((blackbox|store|adapter|lint):([a-z0-9-]+)/([a-z0-9-]+))`(.*)$')
SUITE = {
    ('blackbox', 'gateway'): 'model-gateway',
    ('adapter', 'channel'): 'channel', ('adapter', 'toolhost'): 'toolhost', ('adapter', 'runtime'): 'runtime',
    ('adapter', 'monitor'): 'monitor', ('adapter', 'session'): 'session', ('adapter', 'memory'): 'memory',
    ('adapter', 'sink'): 'sink', ('adapter', 'erasure'): 'erasure', ('adapter', 'lease'): 'runtime',
}
DEFAULT = {'blackbox': 'core-blackbox', 'store': 'store', 'adapter': 'adapter', 'lint': 'lint'}


# rules that name the check in their fixtures field
named_by = collections.defaultdict(set)
for r in rows:
    if r.get('status') == 'active':
        for fx in r.get('fixtures') or []:
            named_by[fx].add(r['id'])

suites = collections.defaultdict(list)
seen = {}
lines = read(os.path.join(ROOT, SRC)).split('\n')
header, section = None, None
for n, line in enumerate(lines, 1):
    if line.startswith('#'):
        section = line.lstrip('#').strip()
    if not line.startswith('|'):
        header = None
        continue
    c = md_cells(line)
    if header is None:
        header = c
        continue
    if set(line) <= set('|-: '):
        continue
    m = NAME.match(c[0])
    if not m:
        continue
    cid, method, area = m.group(1), m.group(2), m.group(3)
    if cid in seen:
        rep.error(f'{SRC}:{n}', f'[suite_check_duplicate] check {cid} is already described on line {seen[cid]}')
        continue
    seen[cid] = n
    rules_in_row = sorted({x.group(0) for x in ID_RE.finditer(' '.join(c[1:]))}, key=id_key)
    rules = sorted(set(rules_in_row) | named_by.get(cid, set()), key=id_key)
    for x in rules:
        if x not in status or status[x]['status'] != 'active':
            rep.error(f'{SRC}:{n}', f'[rule_not_active] {cid}: rule {x} is not active')
    versions = sorted({status[x]['version'] for x in rules if x in status and status[x]['status'] == 'active'})
    entry = {'id': cid, 'method': method, 'rules': rules, 'version': versions[0] if versions else None,
             'section': section, 'source': f'{SRC}:{n}'}
    note = m.group(5).strip()
    if note:
        entry['note'] = ' '.join(note.split())
    for h, v in zip(header[1:], c[1:]):
        key = h.strip() or 'cell'
        if key == 'Rules':
            continue
        entry.setdefault('spec', {})[key] = ' '.join(v.split())
    suite = SUITE.get((method, area), DEFAULT[method])
    suites[(suite, area)].append(entry)

for cid, rids in sorted(named_by.items()):
    m = re.match(r'^(blackbox|store|adapter|lint):', cid)
    if m and cid not in seen:
        v = sorted({status[r]['version'] for r in rids})
        rep.note(cid, f'[suite_check_undescribed] the check is not described in {SRC} (rules {", ".join(sorted(rids, key=id_key))}, {v[0]})')

check = '--check' in sys.argv
HEAD = '# Generated by ci/gen_suites.py from the tables of {src}. Do not edit by hand.\n'
base = os.path.join(ROOT, 'conformance', 'suites')
wanted = set()
for (suite, area), entries in sorted(suites.items()):
    path = os.path.join(base, suite, f'{area}.yaml')
    wanted.add(path)
    doc = {'suite': suite, 'area': area, 'source': SRC, 'checks': entries}
    out = HEAD.format(src=SRC) + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=120)
    old = read(path) if os.path.exists(path) else None
    if old == out:
        continue
    if check:
        rep.error(rel(path), '[generated_stale] does not match the tables: run python3 ci/gen_suites.py')
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(out)
        rep.note(rel(path), f'[generated_written] rebuilt, checks {len(entries)}')
if os.path.isdir(base):
    for dp, dn, fn in os.walk(base):
        for f in fn:
            p = os.path.join(dp, f)
            if f.endswith('.yaml') and read(p).startswith('# Generated by ci/gen_suites.py') and p not in wanted:
                rep.error(rel(p), '[generated_orphan] generated suite without rows in the tables: delete the file')
rep.finish(limit=400)
