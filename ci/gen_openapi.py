"""Builds the OpenAPI 3.1 description of P1 (MAN-12) from the operation map.

The description spec/bindings/http/p1.openapi.json has no types of its own: every request
and answer body is a reference to its spec/model schema file, and paths, headers, the
multipart body of file.put, the byte answer of file.get and problem details follow
spec/bindings/http/README.md. It is generated from the P1 rows of spec/ports/operations.yaml,
so the map stays the one source of P1 operations; the additive check of schemas (MAN-3)
covers the bodies.

  python3 ci/gen_openapi.py          rebuild the description
  python3 ci/gen_openapi.py --check  check that the description matches the map
"""
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, Report, load_yaml, read, rel

rep = Report('openapi')
OUT = os.path.join(ROOT, 'spec', 'bindings', 'http', 'p1.openapi.json')
MODEL_REL = '../../model/'


def ref(name):
    return {'$ref': f'{MODEL_REL}{name}.schema.json'}


def operation(e):
    op = e['op']
    params = []
    if e.get('lease') is True:
        params.append({'$ref': '#/components/parameters/BotaruLease'})
    elif e.get('lease'):
        # A descriptive lease names callers that have no lease, so the header is optional there.
        params.append({'$ref': '#/components/parameters/BotaruLeaseOptional'})
    if e.get('on_behalf'):
        params += [{'$ref': '#/components/parameters/BotaruOnBehalf'}, {'$ref': '#/components/parameters/BotaruChat'},
                   {'$ref': '#/components/parameters/BotaruMessage'}]
    params.append({'$ref': '#/components/parameters/traceparent'})
    if op == 'file.put':
        body = {'required': True, 'content': {'multipart/form-data': {'schema': {
            'type': 'object', 'required': ['meta', 'content'],
            'properties': {'meta': ref(e['request']), 'content': {'type': 'string', 'contentMediaType': 'application/octet-stream'}}},
            'encoding': {'meta': {'contentType': 'application/json'}}}}}
    else:
        body = {'required': True, 'content': {'application/json': {'schema': ref(e['request'])}}}
    if op == 'file.get':
        ok = {'description': 'The file bytes; metadata in headers (spec/bindings/http/README.md).',
              'headers': {'Botaru-File-Ref': {'required': True, 'description': 'file_ref of the p1-file-get-response schema.',
                                              'schema': {'$ref': f'{MODEL_REL}common.schema.json#/$defs/file_ref'}},
                          'Botaru-Data-Mark': {'required': True, 'description': 'data_mark of the p1-file-get-response schema.',
                                               'schema': {'$ref': f'{MODEL_REL}common.schema.json#/$defs/data_mark'}}},
              'content': {'application/octet-stream': {'schema': {'type': 'string', 'contentMediaType': 'application/octet-stream'}}}}
    else:
        ok = {'description': 'Success.', 'content': {'application/json': {'schema': ref(e['response'])}}}
    out = {'operationId': e['id'], 'summary': f'P1 {op}', 'x-botaru-since': e['since'],
           'x-botaru-rules': list(e.get('rules') or []), 'parameters': params, 'requestBody': body,
           'responses': {'200': ok, 'default': {'$ref': '#/components/responses/Problem'}}}
    if e.get('credential'):
        out['description'] = f'Authorization carries the {e["credential"]} instead of the worker token.'
    if e.get('idempotent_by'):
        out['x-botaru-idempotent-by'] = e['idempotent_by']
    return out


def header(name, desc, required=False):
    return {'name': name, 'in': 'header', 'required': required, 'description': desc, 'schema': {'type': 'string', 'maxLength': 2000}}


def build():
    entries = load_yaml(os.path.join(ROOT, 'spec', 'ports', 'operations.yaml'))['entries']
    paths = {}
    for e in entries:
        if e['port'] == 'P1':
            paths[f'/v1/p1/{e["op"]}'] = {'post': operation(e)}
    return {
        'openapi': '3.1.0',
        'info': {'title': 'botaru P1 WorkerProtocol', 'version': 'v1',
                 'description': 'Generated by ci/gen_openapi.py from spec/ports/operations.yaml (MAN-12). '
                                'The wire rules are in spec/bindings/http/README.md; bodies are spec/model schemas.'},
        'jsonSchemaDialect': 'https://json-schema.org/draft/2020-12/schema',
        'security': [{'bearer': []}],
        'paths': paths,
        'components': {
            'securitySchemes': {'bearer': {'type': 'http', 'scheme': 'bearer',
                                           'description': 'The worker token, or the handle named by the operation.'}},
            'parameters': {
                'BotaruLease': header('Botaru-Lease', 'The holder\'s current lease token.', True),
                'BotaruLeaseOptional': header('Botaru-Lease', 'The holder\'s current lease token; '
                                              'sent by callers under a lease, absent for the callers the map row names without one.'),
                'BotaruOnBehalf': header('Botaru-On-Behalf', 'Identity of the person verified by the channel.', True),
                'BotaruChat': header('Botaru-Chat', 'The chat of the press or command: direct:<id> or group:<id>.', True),
                'BotaruMessage': header('Botaru-Message', 'The channel message of a card button press; '
                                        'required for a button press, absent for a typed command.'),
                'traceparent': header('traceparent', 'W3C trace context; decides nothing (OBS-3).'),
            },
            'responses': {'Problem': {'description': 'A refusal: problem details (RFC 9457) with a reason from spec/model/reasons.yaml.',
                                      'content': {'application/problem+json': {'schema': {
                                          '$ref': f'{MODEL_REL}common.schema.json#/$defs/problem'}}}}},
        },
    }


text = json.dumps(build(), indent=2, ensure_ascii=False) + '\n'
if '--check' in sys.argv:
    if not os.path.exists(OUT) or read(OUT) != text:
        rep.error(rel(OUT), '[generated_stale] the P1 OpenAPI description does not match the operation map: run python3 ci/gen_openapi.py')
    else:
        for path, item in build()['paths'].items():
            for side in (item['post']['requestBody']['content'], item['post']['responses']['200'].get('content', {})):
                for media in side.values():
                    for r in [media['schema'].get('$ref')] + [p.get('$ref') for p in media['schema'].get('properties', {}).values()]:
                        if r and r.startswith(MODEL_REL) and not os.path.exists(os.path.join(ROOT, 'spec', 'model', r[len(MODEL_REL):])):
                            rep.error(rel(OUT), f'[openapi_ref_missing] {path}: {r} does not exist')
    rep.info(f'P1 operations {len(build()["paths"])}')
else:
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    rep.info(f'written {rel(OUT)}')
rep.finish()
